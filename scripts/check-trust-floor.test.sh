#!/bin/sh
# Fixtures for check-trust-floor.sh: each case writes a lockfile and checks
# the script's exit status (0 ok or warning only, 1 below the floor).
set -eu

script="$(dirname "$0")/check-trust-floor.sh"
dir="$(mktemp -d)"
trap 'rm -rf "$dir"' EXIT
failures=0

# expect <status> <description> <lockfile contents>
expect() {
    printf '%s' "$3" > "$dir/Cargo.lock"
    status=0
    sh "$script" "$dir/Cargo.lock" > "$dir/out" 2>&1 || status=$?
    if [ "$status" -eq "$1" ]; then
        echo "ok   $2"
    else
        echo "FAIL $2: exit $status, expected $1"
        sed 's/^/     /' "$dir/out"
        failures=$((failures + 1))
    fi
}

# package <name> <version>, in cargo's own layout
package() {
    printf '[[package]]\nname = "%s"\nversion = "%s"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n\n' "$1" "$2"
}

header="$(printf '# This file is automatically @generated by Cargo.\nversion = 4\n\n')"

expect 1 "webpki-roots 1.0.9" "$header
$(package webpki-roots 1.0.9)"
expect 0 "webpki-roots 1.0.10" "$header
$(package webpki-roots 1.0.10)"
expect 1 "webpki-root-certs 1.0.2" "$header
$(package webpki-root-certs 1.0.2)"
expect 0 "webpki-roots 0.25.4 warns" "$header
$(package webpki-roots 0.25.4)"
expect 1 "rustls-webpki 0.103.15" "$header
$(package rustls-webpki 0.103.15)"
expect 0 "rustls-webpki 0.103.16" "$header
$(package rustls-webpki 0.103.16)"
expect 0 "rustls-webpki 0.102.8 warns" "$header
$(package rustls-webpki 0.102.8)"
expect 0 "rustls-webpki 0.104.0" "$header
$(package rustls-webpki 0.104.0)"
expect 1 "below the floor after other packages" "$header
$(package ring 0.17.14)
$(package webpki-roots 1.0.9)
$(package zeroize 1.8.1)"

# The same failing lock in layouts cargo accepts without rewriting.
expect 1 "CRLF line endings" "$(package webpki-roots 1.0.9 | awk '{ printf "%s\r\n", $0 }')"
expect 1 "no spaces around =" '[[package]]
name="webpki-roots"
version="1.0.9"
'
expect 1 "single-quoted strings" "[[package]]
name = 'webpki-roots'
version = '1.0.9'
"
expect 1 "version before name" '[[package]]
version = "1.0.9"
name = "webpki-roots"
source = "registry+https://github.com/rust-lang/crates.io-index"
'
expect 1 "version before name, last entry without trailing newline" '[[package]]
name = "ring"
version = "0.17.14"

[[package]]
version = "1.0.9"
name = "webpki-roots"'

# A version key outside a package entry is not a package version.
expect 0 "lockfile version key" 'version = 4

[[package]]
name = "webpki-roots"
version = "1.0.10"
'

status=0
sh "$script" "$dir/missing.lock" > /dev/null 2>&1 || status=$?
if [ "$status" -eq 2 ]; then echo "ok   missing lock exits 2"; else
    echo "FAIL missing lock: exit $status, expected 2"; failures=$((failures + 1)); fi

[ "$failures" -eq 0 ]
